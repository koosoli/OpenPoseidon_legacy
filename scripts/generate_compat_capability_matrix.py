#!/usr/bin/env python3
"""Generate the COMPAT-C1 compatibility capability matrix from the ledger.

    python scripts/generate_compat_capability_matrix.py            # write
    python scripts/generate_compat_capability_matrix.py --check    # verify, exit 1 on drift

The roadmap forbids reporting "Arma 3 supported" and requires a matrix item naming
its fixture, limitation and verification commit. It also requires that any
compatibility percentage name its exact denominator. Both are easy to promise and
easy to lose, so neither is written by hand here: the claims live in the ledger as
structured `capability_claims`, and this only formats them.

The derivation is the requirement, not a formatting preference. A hand-maintained
capability table is exactly what RND-030 found had drifted from reality, and a
compatibility claim is worse than a feature claim because a reader cannot check it
without the corpus.

`--check` regenerates and diffs without writing, so CI fails on drift.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LEDGER = ROOT / "docs/roadmap/status-ledger.yaml"
OUTPUT = ROOT / "docs/roadmap/compat-c1-capability-matrix.md"
OVERLAY_ID = "COMPAT-C1-EXEC-001"

# What each status means, stated here rather than left to the reader's assumption.
STATUS_MEANING = {
    "VALIDATED": "Exercised against the reference corpora with recorded evidence.",
    "PARTIAL": "Works for a stated subset; the gap is named.",
    "UNVERIFIED": "Implemented, but nothing has confirmed it. Treat as unproven.",
    "UNSUPPORTED": "Deliberately not implemented yet.",
    "UNTESTED": "No fixture in the corpora exercises it.",
    "CAPTURED_NOT_APPLIED": "Read and preserved, but not acted on.",
    "CAPTURED_NOT_INTERPRETED": "Read and preserved; its meaning is not claimed.",
    "NOT_PRODUCED": "Deliberately not derived; a consumer must opt in explicitly.",
    "SUPERSEDED": (
        "True at its own verification commit, and later work moved past it. "
        "The denominator names the ticket that now holds the live claim."
    ),
}


def ticket_blocks(text: str) -> list[tuple[str, str]]:
    blocks: list[tuple[str, str]] = []
    current, buf = None, []
    for line in text.splitlines():
        if line.startswith("  - id: "):
            if current:
                blocks.append((current, "\n".join(buf)))
            current, buf = line.removeprefix("  - id: ").strip(), []
        elif current:
            buf.append(line)
    if current:
        blocks.append((current, "\n".join(buf)))
    return blocks


def field(block: str, name: str) -> str:
    match = re.search(rf"^    {name}: (.*)$", block, re.MULTILINE)
    return match.group(1).strip() if match else ""


def claims(block: str) -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    section = re.search(r"^    capability_claims:\n(.*?)(?=^    \w+:)", block + "\n    end:", re.MULTILINE | re.DOTALL)
    if not section:
        return out
    current: dict[str, str] = {}
    pending_denominator = False
    for line in section.group(1).splitlines():
        stripped = line.strip()
        if stripped.startswith("- capability: "):
            if current:
                out.append(current)
            current = {"capability": stripped.removeprefix("- capability: ")}
            pending_denominator = False
        elif stripped.startswith("status: "):
            current["status"] = stripped.removeprefix("status: ")
        elif stripped.startswith("denominator:"):
            pending_denominator = True
        elif pending_denominator and stripped:
            current["denominator"] = current.get("denominator", "") + (" " if current.get("denominator") else "") + stripped
    if current:
        out.append(current)
    return out


def render(rows: list[tuple[str, dict[str, str], str, str]]) -> str:
    used = sorted({row[1].get("status", "?") for row in rows})
    lines = [
        "# COMPAT-C1 compatibility capability matrix",
        "",
        "<!-- GENERATED by scripts/generate_compat_capability_matrix.py -- do not edit. -->",
        "",
        "Derived from `docs/roadmap/status-ledger.yaml`. Every row names the ticket that",
        "produced it, its verification commit, and **the denominator its claim was",
        "measured over**. A compatibility claim without a denominator is not a claim, and",
        'the roadmap forbids reporting anything as broadly as "Arma 3 supported".',
        "",
        "Read a status as a statement about *this build against the owner's reference",
        "corpora*, not about a game.",
        "",
        "## Status meanings",
        "",
        "| Status | Meaning |",
        "|---|---|",
    ]
    for status in used:
        lines.append(f"| `{status}` | {STATUS_MEANING.get(status, 'Undocumented status.')} |")
    lines += [
        "",
        "## Capabilities",
        "",
        "| Capability | Status | Denominator / limitation | Ticket | Verified at |",
        "|---|---|---|---|---|",
    ]
    for capability, claim, ticket, commit in rows:
        lines.append(
            f"| `{capability}` | `{claim.get('status','?')}` | {claim.get('denominator','')} "
            f"| {ticket} | `{commit or '-'}` |"
        )
    lines += [
        "",
        "## What no row here claims",
        "",
        "No row claims broad Arma-generation compatibility. A rendered static ODOL 73",
        "model proves only the explicitly stated fixture and limitations; material, texture,",
        "alpha, winding, normal, section-range and additional-UV validation remain separate",
        "claims. The winding convention for P3DM geometry stays unverified until a P3DM",
        "model reaches the screen.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = LEDGER.read_text(encoding="utf-8")
    rows: list[tuple[str, dict[str, str], str, str]] = []
    for ticket, block in ticket_blocks(text):
        if field(block, "overlay") != OVERLAY_ID:
            continue
        commit = field(block, "verification_commit")
        for claim in claims(block):
            rows.append((claim["capability"], claim, ticket, "" if commit == "null" else commit))
    if not rows:
        sys.exit("no capability_claims found in the COMPAT-C1 ledger records")
    rows.sort(key=lambda r: (r[2], r[0]))

    rendered = render(rows)
    if args.check:
        if not OUTPUT.is_file():
            print(f"missing {OUTPUT.relative_to(ROOT).as_posix()}", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            print("capability matrix is stale; regenerate it", file=sys.stderr)
            return 1
        print(f"capability matrix current: {len(rows)} claims")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()} ({len(rows)} claims)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
