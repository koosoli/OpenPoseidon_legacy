"""Tidewater's humpback whale for the @OP_TidewaterWildlife pack (owner, 2026-10-19: "port them over as well").

Run once against a Tidewater checkout (dgreenheck/tidewater, MIT, (c) DRG Software Solutions LLC); the output is
committed under content/default-packs/tidewater-wildlife/source, so the engine build needs no Tidewater:

    python scripts/default-content/export_tidewater_whale.py <tidewater checkout> content/default-packs/tidewater-wildlife/source

Provenance (Tidewater CREDITS.md): the whale is Tidewater's own procedural model, generated by its authors' scripts;
its proportions follow published humpback anatomy and its side profile was traced from a NOAA Fisheries
illustration (a US government work in the public domain). No game's content is used.

What it writes:
* humpback.bin.gz -- the runtime file (Humpback.cpp reads it uncompressed from the pack): the spine rig Tidewater's
  Whale.js builds at load (40 frames from the snout to past the flukes, each frame's rest height on the centre
  line), the flipper roots and the blowhole, and the three levels of detail as plain vertex arrays. Tidewater's
  relief map (tubercles, ventral pleats, barnacles; humpback_height.png, applied in its vertex shader) is baked into
  the finest level's positions here.
* humpback_albedo.png -- the baked skin, 4096 x 2048 down to 2048 x 1024 (rgb; Tidewater keeps roughness in alpha).

Runtime file, little endian: 'OPWH', u32 version (1), u32 K, u32 root index, f32 zHead, f32 dz, f32 notchZ,
f32 length, f32[3] blowhole, f32[3] left flipper root, f32[3] right flipper root, f32[K] rest y, u32 levels, then
per level u32 vertices, u32 indices; then per level the vertices (f32 position 3, normal 3, uv 2, rig 4: rest z,
part (0 body, 1 left flipper, 2 right flipper), flipper flex, unused) and the u32 indices.
"""

import gzip
import json
import struct
import sys
from pathlib import Path

import numpy as np
from PIL import Image

K = 40  # Whale.js spine frames


def main():
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    src = root / "public" / "models" / "whale"
    m = json.loads((src / "humpback.json").read_text())
    data = (src / "humpback.bin").read_bytes()
    out.mkdir(parents=True, exist_ok=True)

    # the rig exactly as Whale._setupRig
    z_head = m["snoutZ"] + 0.15
    z_tail = m["notchZ"] - 1.2
    dz = (z_head - z_tail) / (K - 1)
    cz, cy = m["centerline"]["z"], m["centerline"]["y"]  # z descending

    def yc_at(z):
        if z >= cz[0]:
            return cy[0]
        for i in range(1, len(cz)):
            if z >= cz[i]:
                return cy[i - 1] + (cy[i] - cy[i - 1]) * (z - cz[i - 1]) / (cz[i] - cz[i - 1])
        return cy[-1]

    rest_y = [yc_at(z_head - k * dz) for k in range(K)]
    root_index = round(z_head / dz)

    # Tidewater's relief: height in 16 bits over R and G (Whale.js `relief`)
    h0, h1 = m["textures"]["heightRange"]
    height = np.asarray(Image.open(src / m["textures"]["height"]).convert("RGBA"), dtype=np.float64) / 255.0
    hh, hw = height.shape[:2]

    def relief(uv):
        # bilinear, clamped; v = 0 is the texture's first row (WebGPU, Tidewater loads it unflipped: measured, the
        # albedo then puts the dark back on the back -- flipped, the back sampled the white belly)
        x = np.clip(uv[:, 0], 0, 1) * (hw - 1)
        y = np.clip(uv[:, 1], 0, 1) * (hh - 1)
        x0, y0 = np.floor(x).astype(int), np.floor(y).astype(int)
        x1, y1 = np.minimum(x0 + 1, hw - 1), np.minimum(y0 + 1, hh - 1)
        fx, fy = (x - x0)[:, None], (y - y0)[:, None]
        tex = (height[y0, x0] * (1 - fx) + height[y0, x1] * fx) * (1 - fy) + (height[y1, x0] * (1 - fx) + height[y1, x1] * fx) * fy
        return (tex[:, 0] * 0.99611 + tex[:, 1] * 0.00389) * (h1 - h0) + h0

    levels = []
    for i, lv in enumerate(m["levels"]):
        n = lv["vertices"]
        pos = np.frombuffer(data, np.float32, n * 3, lv["position"]).reshape(-1, 3).astype(np.float64)
        nrm = np.frombuffer(data, np.int16, n * 3, lv["normal"]).reshape(-1, 3).astype(np.float64) / 32767.0
        nrm /= np.maximum(np.linalg.norm(nrm, axis=1, keepdims=True), 1e-9)
        uv = np.frombuffer(data, np.float32, n * 2, lv["uv"]).reshape(-1, 2).astype(np.float64)
        rig = np.frombuffer(data, np.float32, n * 4, lv["rig"]).reshape(-1, 4).astype(np.float64)
        idx = np.frombuffer(data, np.uint32, lv["indices"], lv["index"])
        if i == 0:
            pos = pos + nrm * relief(uv)[:, None]
        levels.append((np.hstack([pos, nrm, uv, rig]).astype(np.float32), idx.astype(np.uint32)))

    head = [b"OPWH", struct.pack("<IIIffff", 1, K, root_index, z_head, dz, m["notchZ"], m["length"])]
    head.append(struct.pack("<3f", *m["blowhole"]))
    head.append(struct.pack("<3f", *m["pectoral"]["left"]["origin"]))
    head.append(struct.pack("<3f", *m["pectoral"]["right"]["origin"]))
    head.append(struct.pack(f"<{K}f", *rest_y))
    head.append(struct.pack("<I", len(levels)))
    for v, ix in levels:
        head.append(struct.pack("<II", len(v), len(ix)))
    body = [v.tobytes() + ix.tobytes() for v, ix in levels]
    (out / "humpback.bin.gz").write_bytes(gzip.compress(b"".join(head + body), 9))

    Image.open(src / m["textures"]["albedo"]).convert("RGB").resize((2048, 1024), Image.LANCZOS).save(out / "humpback_albedo.png")
    print(f"humpback: levels {[len(v) for v, _ in levels]} vertices, rest root {root_index}, dz {dz:.3f} m")


if __name__ == "__main__":
    main()
